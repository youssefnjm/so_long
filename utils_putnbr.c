#include "so_long.h"

void	ft_putnbr(int n)
{
	char	num;

	if (n == -2147483648)
		write(1, "-2147483648", 11);
	else if (n < 0)
	{
		write(1, "-", 1);
		ft_putnbr(-n);
	}
	else if (n > 9)
	{
		ft_putnbr(n / 10);
		ft_putnbr(n % 10);
	}
	else
	{
		num = n + 48;
		write(1, &num, 1);
	}
}
